const fs = require('fs');
const path = 'd:/Home form/ako-light-cline/lib/auth/sms.ts';

const lines = [];
lines.push('/**');
lines.push(' * SMS delivery seam for phone-number OTP codes - sms.ir Verify integration.');
lines.push(' *');
lines.push(' * better-auth phoneNumber plugin delivers codes through sendOtpSms.');
lines.push(' * API: POST https://api.sms.ir/v1/send/verify');
lines.push(' * Mobile: digits only, no +, no leading 0. 09xxxxxxxxx -> 9xxxxxxxxx (10 digits).');
lines.push(' * Sandbox: only template 123456, no actual SMS delivered.');
lines.push(' * When SMSIR_API_KEY set to Sandbox key, log [DEV OTP] to console.');
lines.push(' */');
lines.push('');
lines.push('const SMSIR_API_KEY_ENV = "SMSIR_API_KEY";');
lines.push('');
lines.push('const SMSIR_VERIFY_TEMPLATE_ID_ENV = "SMSIR_VERIFY_TEMPLATE_ID";');
lines.push('');
lines.push('const SMSIR_SANDBOX_DEFAULT_TEMPLATE_ID = "123456";');
lines.push('');
lines.push('export function isSmsIrConfigured(): boolean {');
lines.push('  return Boolean(process.env[SMSIR_API_KEY_ENV]?.trim());');
lines.push('}');
lines.push('');
lines.push('/**');
lines.push(' * Heuristic: Sandbox vs Production key detection.');
lines.push(' * Treat as Sandbox when SMSIR_VERIFY_TEMPLATE_ID is still 123456 (the');
lines.push(' * documented Sandbox default) AND the key is non-empty.');
lines.push(' */');
lines.push('function isSandboxKey(): boolean {');
lines.push('  const key = process.env[SMSIR_API_KEY_ENV]?.trim();');
lines.push('  const templateId = process.env[SMSIR_VERIFY_TEMPLATE_ID_ENV]?.trim();');
lines.push('  if (!key) return false;');
lines.push('  return templateId === SMSIR_SANDBOX_DEFAULT_TEMPLATE_ID;');
lines.push('}');
lines.push('');
lines.push('/**');
lines.push(' * Normalize Iranian mobile to sms.ir format: 10 digits, no +, no leading 0.');
lines.push(' * 0919xxxx904 -> 919xxxx904, +98919xxxx904 -> 919xxxx904, 919xxxx904 -> 919xxxx904');
lines.push(' */');
lines.push('function normalizeMobile(phoneNumber: string): string {');
lines.push('  const digits = phoneNumber.replace(/[^0-9]/g, "");');
lines.push('  if (digits.startsWith("0") && digits.length === 11) {');
lines.push('    return digits.slice(1);');
lines.push('  }');
lines.push('  if (digits.length === 10) {');
lines.push('    return digits;');
lines.push('  }');
lines.push('  return digits;');
lines.push('}');
lines.push('');

fs.writeFileSync(path, lines.join('\n'));
console.log('Part 1 written: ' + lines.length + ' lines');
